const fs = require('node:fs')
const assert = require('node:assert/strict')
const sfc = require('vue/compiler-sfc')
for (const file of ['src/components/HomeWorkspace.vue', 'src/pages/role/index.vue']) {
  const source = fs.readFileSync(file, 'utf8')
  assert.ok(!source.includes('/pages/ops/materialApply'), `${file}: no standalone pick entry`)
  assert.ok(!source.includes('/pages/ops/materialReturn'), `${file}: no standalone return entry`)
  assert.ok(source.includes('/pages/stock/materialApply'), 'stock management remains')
  const { descriptor } = sfc.parse(source, { filename: file })
  sfc.compileScript(descriptor, { id: 'context-entries' })
  assert.deepEqual(sfc.compileTemplate({ source: descriptor.template.content, filename: file, id: 'context-entries' }).errors, [])
}
const project = fs.readFileSync('src/pages/ops/projectDetail.vue', 'utf8')
assert.ok(project.includes('/pages/ops/materialApply?periodId='))
assert.ok(project.includes('/pages/ops/materialReturn?periodId='))
const repair = fs.readFileSync('src/pages/ops/components/preview/OpsWorkflow.vue', 'utf8')
assert.ok(repair.includes("openMaterials('领料')"))
assert.ok(repair.includes("openMaterials('还料')"))
console.log('PASS standalone entries removed; project, repair and stock management entries retained')
