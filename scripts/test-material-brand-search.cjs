const fs = require('node:fs')
const assert = require('node:assert/strict')
const ts = require('typescript')
const helper = {}
new Function('exports', ts.transpile(fs.readFileSync('src/utils/materialBrandSearch.ts', 'utf8'), { module: ts.ModuleKind.CommonJS }))(helper)
const brands = helper.materialBrandMap({ result: [{ value: 'b1', text: '海康 Hikvision' }, { value: 'b2', label: '大华' }] })
const rows = [{ id: 1, name: '摄像头', brand: 'b1' }, { id: 2, brand: 'b2' }]
assert.deepEqual(helper.filterMaterialSearch(rows, ' 海康 ', brands), [rows[0]])
assert.deepEqual(helper.filterMaterialSearch(rows, 'HIK', brands), [rows[0]])
assert.deepEqual(helper.filterMaterialSearch(rows, '大华', brands), [rows[1]])
assert.equal(helper.filterMaterialSearch(rows, '', brands), rows)
assert.deepEqual(helper.filterMaterialSearch([{ brand_dictText: '其他品牌' }], '其他', {}), [{ brand_dictText: '其他品牌' }])
assert.throws(() => helper.materialBrandMap({ success: false, result: [] }))
assert.throws(() => helper.materialBrandMap({ result: {} }))
const sfc = require('vue/compiler-sfc')
const source = fs.readFileSync('src/pages/ops/materialApply.vue', 'utf8')
const { descriptor, errors } = sfc.parse(source)
assert.deepEqual(errors, [])
sfc.compileScript(descriptor, { id: 'brand' })
const ast = ts.createSourceFile('brand.ts', descriptor.scriptSetup.content, ts.ScriptTarget.Latest, true)
const node = ast.statements.find(n => ts.isVariableStatement(n) && n.declarationList.declarations.some(d => d.name.getText(ast) === 'filteredMaterialList'))
const run = new Function('computed', 'isProjectUsage', 'reworkId', 'materialList', 'materialKeyword', 'brandNames', 'filterMaterialSearch', ts.transpile(node.getText(ast)) + '; return filteredMaterialList')
const ref = value => ({ value })
assert.equal(run(fn => fn(), ref(true), ref(''), ref(rows), ref('后端命中的品牌别名'), ref(brands), helper.filterMaterialSearch), rows)
assert.deepEqual(run(fn => fn(), ref(true), ref('r1'), ref(rows), ref('海康'), ref(brands), helper.filterMaterialSearch), [rows[0]])
assert.deepEqual(sfc.compileTemplate({ source: descriptor.template.content, filename: 'materialApply.vue', id: 'brand' }).errors, [])
console.log('Mobile material brand search regression passed')
