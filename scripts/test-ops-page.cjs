// Component-state tests: execute the actual Vue setup with only visual child imports stubbed.
const fs = require('node:fs')
const vm = require('node:vm')
const assert = require('node:assert/strict')
const ts = require('typescript')
const vue = require('vue')
const sfc = require('../node_modules/.pnpm/@vue+compiler-sfc@3.4.21/node_modules/@vue/compiler-sfc')
const transpile = source => ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true } }).outputText
const flowBox = { exports: {} }
vm.runInNewContext(transpile(fs.readFileSync('src/pages/ops/components/preview/repairWorkflow.ts', 'utf8')), flowBox)
const path = 'src/pages/ops/components/preview/OpsWorkflow.vue'
const parsed = sfc.parse(fs.readFileSync(path, 'utf8'), { filename: path })
assert.equal(parsed.errors.length, 0)
const script = sfc.compileScript(parsed.descriptor, { id: 'ops-page-test' })
const compiled = sfc.compileTemplate({ source: parsed.descriptor.template.content, filename: path, id: 'ops-page-test', compilerOptions: { bindingMetadata: script.bindings } })
assert.equal(compiled.errors.length, 0)
const box = { exports: {}, setInterval: () => 0, clearInterval: () => {}, require: name => {
  if (name === 'vue') return { ...vue, onBeforeUnmount: () => {} }
  if (name === './repairWorkflow') return flowBox.exports
  if (name.endsWith('.vue')) return {}
  return require(name)
} }
vm.runInNewContext(transpile(script.content), box)
async function main() {
  const events = []
  const scope = vue.effectScope()
  const page = scope.run(() => box.exports.default.setup({ canManage: false }, { expose: () => {}, emit: (...args) => events.push(args) }))
  page.openHomeEntry('records')
  assert.equal(page.actor.value.role, 'technician')
  assert.equal(page.filtered.value.length, 15)
  assert.equal(page.paged.value.length, 5)
  assert.equal(page.pageCount.value, 3)
  console.log('PASS default repair entry shows 15 tasks and three pages')
  page.openCase(page.filtered.value[0])
  assert.equal(page.footerActions.value[0].text, '开始维修')
  assert(page.canShowMore.value)
  assert.equal(page.moreGroups.value.length, 3)
  const personnel = page.moreGroups.value.find(g => g.title === '人员与物料')
  assert.equal(personnel.items.length, 3)
  personnel.items[0].action()
  assert.equal(page.screen.value, 'assistance')
  assert.equal(page.footerActions.value[0].text, '提交协助申请')
  page.submitAssistance([{ id: 'company-test', name: '测试用户' }], '现场协助')
  assert.equal(page.screen.value, 'detail')
  assert.equal(page.selected.value.assistanceRequests.length, 1)
  personnel.items[1].action()
  assert.equal(page.title.value, '领料申请')
  page.back()
  personnel.items[2].action()
  assert.equal(page.title.value, '还料申请')
  page.back()
  page.footerActions.value[0].action()
  assert.equal(page.screen.value, 'log')
  assert.equal(page.footerActions.value[0].text, '保存并结束打卡')
  page.back()
  assert.equal(page.footerActions.value[0].text, '继续填写日志')
  console.log('PASS fixed footer follows repair state and more menu is grouped')
  page.switchActor(0)
  await vue.nextTick()
  assert.equal(page.screen.value, 'reports')
  assert(events.some(e => e[0] === 'role-change' && e[1] === 'reporter'))
  page.openHomeEntry('records')
  assert.equal(page.screen.value, 'reports')
  page.openCase(page.filtered.value[0])
  assert.equal(page.footerActions.value.length, 0)
  assert(!page.canShowMore.value)
  console.log('PASS reporter cannot enter repair task or receive owner controls')
  page.switchActor(3)
  page.openHomeEntry('records')
  assert.equal(page.filtered.value.length, 30)
  page.pendingOnly.value = true
  assert(page.filtered.value.length > 0)
  assert(page.filtered.value.every(c => c.completion === '待审批' || (c.quoteState === '报价审批中' && c.quoteStep === '主管')))
  page.openCase(page.filtered.value[0])
  assert(page.footerActions.value[0].text.startsWith('审批'))
  assert(!page.canShowMore.value)
  console.log('PASS supervisor pending filter and approval-only footer')
  page.switchActor(4)
  assert.equal(page.screen.value, 'records')
  assert.equal(page.filtered.value.length, 2)
  page.openCase(page.filtered.value[0])
  page.footerActions.value[0].action()
  assert.equal(page.screen.value, 'approval')
  page.review(true)
  assert.equal(page.screen.value, 'records')
  assert.equal(page.filtered.value.length, 1)
  console.log('PASS director approval returns to repair list, no separate quote route')
  const home = fs.readFileSync('src/components/HomeWorkspace.vue', 'utf8')
  const entries = home.slice(home.indexOf('const opsEntries'), home.indexOf('function openOps'))
  assert(entries.includes("label: '报修管理'"))
  assert(!entries.includes("key: 'quotes'")); assert(!entries.includes("key: 'create'"))
  assert(entries.includes("opsDemoRole.value !== 'reporter'"))
  console.log('PASS home entries consolidated and reporter repair entry hidden')
  scope.stop()
}
main().catch(error => { console.error(error); process.exitCode = 1 })
